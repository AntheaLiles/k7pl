"""Apply a narrow compatibility shim to pinned Klean output for Lean 4.34.0.

Klean 7.1.337 emits a local ByteArray.decEq definition that collides with
the same declaration provided by Lean 4.34.0. Remove only that generated
definition, preserving the generated DecidableEq SortBytes instance which
uses the Lean-provided declaration. If the expected template changes, fail
closed and require a human review instead of silently editing arbitrary code.
"""

from __future__ import annotations

import argparse
from pathlib import Path

DECLARATION = "def ByteArray.decEq (a b : ByteArray) : Decidable (Eq a b) :="
INSTANCE = "instance: DecidableEq SortBytes := ByteArray.decEq"


def patch_text(source: str) -> str:
    """Remove the exact duplicate generated helper or fail closed."""
    if source.count(DECLARATION) != 1:
        raise ValueError(
            "expected exactly one Klean-generated ByteArray.decEq declaration; "
            "generator output changed, refusing to patch"
        )
    if source.count(INSTANCE) != 1:
        raise ValueError(
            "expected exactly one DecidableEq SortBytes instance after the helper; "
            "generator output changed, refusing to patch"
        )

    start = source.index(DECLARATION)
    end = source.index(INSTANCE, start)
    if end <= start:
        raise ValueError("generated instance occurs before ByteArray.decEq declaration")

    removed = source[start:end]
    if not removed.startswith(DECLARATION + "\n"):
        raise ValueError("unexpected ByteArray.decEq declaration formatting")
    if "instance:" in removed or "def " in removed[len(DECLARATION) :]:
        raise ValueError("unexpected extra declaration in compatibility shim span")

    patched = source[:start] + source[end:]
    if DECLARATION in patched or INSTANCE not in patched:
        raise AssertionError("compatibility shim postcondition failed")
    return patched


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("prelude", type=Path, help="Klean-generated Prelude.lean")
    args = parser.parse_args()

    source = args.prelude.read_text(encoding="utf-8")
    patched = patch_text(source)
    args.prelude.write_text(patched, encoding="utf-8")
    print(
        f"Patched {args.prelude}: removed duplicate declaration {DECLARATION!r}; "
        f"retained instance {INSTANCE!r} to use the declaration provided by Lean 4.34.0."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
