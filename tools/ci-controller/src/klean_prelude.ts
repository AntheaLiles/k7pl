/**
 * Narrow compatibility shim for pinned Klean output, ported
 * faithfully from scripts/ci/patch_klean_prelude.py (CC0-1.0,
 * preserved here — this file is NOT CECILL-2.1 like the rest of
 * the controller).
 *
 * COMPATIBILITY PROBE ONLY — NOT A SOUNDNESS ARGUMENT.
 *
 * Klean 7.1.337 emits a local ByteArray.decEq definition that
 * collides with the same declaration provided by Lean 4.34.0.
 * This shim removes only that generated definition, preserving
 * the generated DecidableEq SortBytes instance which uses the
 * Lean-provided declaration. If the expected template changes,
 * it fails closed and requires a human review instead of
 * silently editing arbitrary code. Nothing in this shim proves
 * anything about K7PL: it only makes pinned generator output
 * compile under a newer Lean. Any output or evidence record
 * produced by this module carries `probe: true` so it can never
 * be mistaken for a soundness claim.
 *
 * Port note: when the instance anchor occurs before the
 * declaration, the Python code raises ValueError("substring not
 * found") from str.index(); this port raises an explicit
 * "generated instance occurs before ByteArray.decEq declaration"
 * error instead. Same outcome (fail closed, non-zero exit),
 * clearer message.
 */

export const DECLARATION =
  "def ByteArray.decEq (a b : ByteArray) : Decidable (Eq a b) :=";
export const INSTANCE = "instance: DecidableEq SortBytes := ByteArray.decEq";

function countOccurrences(source: string, needle: string): number {
  return source.split(needle).length - 1;
}

/**
 * Remove the exact duplicate generated helper or fail closed.
 * Mirrors patch_text() in the Python original, including its
 * error messages and the postcondition check.
 */
export function patchText(source: string): string {
  if (countOccurrences(source, DECLARATION) !== 1) {
    throw new Error(
      "expected exactly one Klean-generated ByteArray.decEq declaration; " +
        "generator output changed, refusing to patch",
    );
  }
  if (countOccurrences(source, INSTANCE) !== 1) {
    throw new Error(
      "expected exactly one DecidableEq SortBytes instance after the helper; " +
        "generator output changed, refusing to patch",
    );
  }

  const start = source.indexOf(DECLARATION);
  const end = source.indexOf(INSTANCE, start);
  if (end <= start) {
    throw new Error(
      "generated instance occurs before ByteArray.decEq declaration",
    );
  }

  const removed = source.slice(start, end);
  if (!removed.startsWith(DECLARATION + "\n")) {
    throw new Error("unexpected ByteArray.decEq declaration formatting");
  }
  if (
    removed.includes("instance:") ||
    removed.slice(DECLARATION.length).includes("def ")
  ) {
    throw new Error("unexpected extra declaration in compatibility shim span");
  }

  const patched = source.slice(0, start) + source.slice(end);
  if (patched.includes(DECLARATION) || !patched.includes(INSTANCE)) {
    throw new Error("compatibility shim postcondition failed");
  }
  return patched;
}

/** Evidence-style report for a shim application. `probe` is always true. */
export interface KleanPreludePatchReport {
  probe: true;
  kind: "klean-prelude-compatibility-probe";
  declaration: string;
  instance: string;
  removed: string;
  patched: string;
  note: string;
}

export const PROBE_NOTE =
  "Compatibility probe only, not a soundness argument: this shim " +
  "removes a duplicate Klean-generated helper so pinned output " +
  "compiles under Lean 4.34.0; it proves nothing about K7PL.";

/** Apply {@link patchText} and describe the change as a probe report. */
export function patchPreludeReport(source: string): KleanPreludePatchReport {
  const patched = patchText(source);
  const start = source.indexOf(DECLARATION);
  const end = source.indexOf(INSTANCE, start);
  return {
    probe: true,
    kind: "klean-prelude-compatibility-probe",
    declaration: DECLARATION,
    instance: INSTANCE,
    removed: source.slice(start, end),
    patched,
    note: PROBE_NOTE,
  };
}

/**
 * CLI parity with the Python script: one positional argument, the
 * Klean-generated Prelude.lean to patch in place. Prints the
 * Python script's human-readable message plus a JSON probe line
 * carrying `probe: true`. Returns a process exit code.
 */
export async function runKleanPreludeCli(argv: string[]): Promise<number> {
  const [prelude] = argv.filter((arg) => !arg.startsWith("--"));
  if (prelude === undefined || argv.length !== 1) {
    console.error(
      "usage: deno run --allow-read --allow-write src/klean_prelude.ts <Prelude.lean>",
    );
    return 2;
  }
  try {
    const source = await Deno.readTextFile(prelude);
    const report = patchPreludeReport(source);
    await Deno.writeTextFile(prelude, report.patched);
    console.log(
      `Patched ${prelude}: removed duplicate declaration '${DECLARATION}'; ` +
        `retained instance '${INSTANCE}' to use the declaration provided by Lean 4.34.0.`,
    );
    console.log(
      "KLEAN-PRELUDE-PROBE " +
        JSON.stringify({
          probe: true,
          kind: report.kind,
          declaration: report.declaration,
          instance: report.instance,
          removedChars: report.removed.length,
          note: report.note,
        }),
    );
    return 0;
  } catch (error) {
    console.error(
      `klean prelude patch failed: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
    return 1;
  }
}

if (import.meta.main) {
  Deno.exit(await runKleanPreludeCli(Deno.args));
}
