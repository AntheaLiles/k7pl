export const LEGACY_PATHS = [
  "archives/",
  "docs/archives/",
  "docs/history/",
  "docs/archive/",
  "docs/journal/",
  "docs/historique/",
  "docs/relectures/",
  "docs/suivi/",
  "docs/recherche/",
  "docs/methode/",
  "docs/bibliographie/",
  "biblio/references.json",
] as const;

export const REQUIRED_DIRS = ["wiki"] as const;

export const REQUIRED_FILES = [
  "wiki/references.json",
  "wiki/HOME.md",
  "wiki/understanding.md",
  "wiki/layers.md",
  "wiki/research.md",
  "wiki/assurance.md",
  "wiki/method.md",
] as const;

export const ENGLISH_ENTRY_POINTS: Readonly<Record<string, string>> = {
  "wiki/HOME.md": "# K7PL Wiki",
  "wiki/understanding.md": "# Understanding K7PL",
  "wiki/layers.md": "# The Three Layers",
  "wiki/research.md": "# Research",
  "wiki/assurance.md": "# Assurance",
  "wiki/method.md": "# Method",
  "wiki/STATUS.md": "# K7PL Status",
  // wiki/STATUS.md is generated by CI, not authored: it is
  // not a required file, but if present its heading must match.
};

export const SCAN_EXTENSIONS = new Set([
  ".md",
  ".py",
  ".sh",
  ".lean",
  ".toml",
  ".yaml",
  ".yml",
  ".cff",
  ".json",
]);

/** Scanned roots; docs/ is deliberately absent (deleted). */
export const SCAN_ROOTS = ["scripts", "tools", ".github", ".claude"] as const;

/** Files exempt from the obsolete-reference scan (the guard itself). */
export const SELF_EXEMPTIONS = new Set([
  "scripts/ci/check_documentation_architecture.py",
  "scripts/ci/test_documentation_architecture.py",
  "tools/ci-controller/src/documentation_architecture.ts",
  "tools/ci-controller/tests/documentation_architecture_test.ts",
]);

async function exists(path: string): Promise<boolean> {
  try {
    await Deno.stat(path);
    return true;
  } catch {
    return false;
  }
}

async function isDirectory(path: string): Promise<boolean> {
  try {
    return (await Deno.stat(path)).isDirectory;
  } catch {
    return false;
  }
}

async function isFile(path: string): Promise<boolean> {
  try {
    return (await Deno.stat(path)).isFile;
  } catch {
    return false;
  }
}

/** Python's read_text with a UnicodeDecodeError fallback to "". */
async function readText(path: string): Promise<string> {
  try {
    return await Deno.readTextFile(path);
  } catch {
    return "";
  }
}

/** Python Path.suffix, lowercased ("" for dotfiles and extensionless names). */
function suffixOf(name: string): string {
  const index = name.lastIndexOf(".");
  if (index <= 0) return "";
  return name.slice(index).toLowerCase();
}

/** Python re.escape, as used for the reported pattern text. */
function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

async function* walkFiles(dir: string): AsyncGenerator<string> {
  for await (const entry of Deno.readDir(dir)) {
    const entryPath = `${dir}/${entry.name}`;
    if (entry.isDirectory) {
      yield* walkFiles(entryPath);
    } else if (entry.isFile) {
      yield entryPath;
    }
  }
}

/**
 * The guard itself: returns the sorted, de-duplicated
 * error list (empty means the architecture check passes).
 * `root` is a filesystem path to the repository root.
 */
export async function check(root: string): Promise<string[]> {
  const errors: string[] = [];
  const cleanRoot = root.replace(/\/+$/, "");

  for (const rel of LEGACY_PATHS) {
    if (await exists(`${cleanRoot}/${rel.replace(/\/$/, "")}`)) {
      errors.push(`legacy path still exists: ${rel}`);
    }
  }

  for (const rel of REQUIRED_DIRS) {
    if (!await isDirectory(`${cleanRoot}/${rel}`)) {
      errors.push(`required directory missing: ${rel}`);
    }
  }

  for (const rel of REQUIRED_FILES) {
    if (!await isFile(`${cleanRoot}/${rel}`)) {
      errors.push(`required file missing: ${rel}`);
    }
  }

  for (const [rel, expected] of Object.entries(ENGLISH_ENTRY_POINTS)) {
    const path = `${cleanRoot}/${rel}`;
    if (!await isFile(path)) continue;
    const text = await readText(path);
    // Python: the first line starting with "# ", stripped.
    const firstHeading = text.split("\n").find((line) =>
      line.startsWith("# ")
    )?.trim() ?? "";
    if (firstHeading !== expected) {
      errors.push(
        `non-English or unexpected entry point heading: ${rel}: '${firstHeading}'`,
      );
    }
  }

  // The legacy-reference scan skips the bare "archives/"
  // marker (LEGACY_PATHS[0]), exactly as the Python
  // original scans LEGACY_PATHS[1:].
  const legacyMarkers = LEGACY_PATHS.slice(1);
  for (const base of SCAN_ROOTS) {
    const basePath = `${cleanRoot}/${base}`;
    if (!await exists(basePath)) continue;
    for await (const filePath of walkFiles(basePath)) {
      const name = filePath.split("/").pop() ?? "";
      if (!SCAN_EXTENSIONS.has(suffixOf(name))) continue;
      const rel = filePath.slice(cleanRoot.length + 1);
      if (SELF_EXEMPTIONS.has(rel)) continue;
      const text = await readText(filePath);
      for (const marker of legacyMarkers) {
        if (text.includes(marker)) {
          errors.push(
            `obsolete path reference in active surface: ${rel}: ${
              escapeRegExp(marker)
            }`,
          );
        }
      }
    }
  }

  return [...new Set(errors)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** Returns a process exit code: 1 with ERROR lines, else 0 with the OK line. */
export async function main(): Promise<number> {
  const repoRoot = new URL("../../../", import.meta.url).pathname.replace(
    /\/$/,
    "",
  );
  const errors = await check(repoRoot);
  if (errors.length > 0) {
    for (const error of errors) console.log(`ERROR: ${error}`);
    return 1;
  }
  console.log("documentation architecture check: OK");
  return 0;
}

if (import.meta.main) {
  Deno.exit(await main());
}
